export const normalizeStation = (name: string) => {
  const cleaned = name
    .replace(/\([^)]*\)/g, '')
    .replace(/역$/, '')
    .replace(/\s/g, '')
    .trim()
  return stationAliases[cleaned] ?? cleaned
}
